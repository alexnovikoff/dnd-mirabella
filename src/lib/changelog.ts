/* История версий для страницы «О проекте». Пишется для участников кампании, а не
 * для разработки: что изменилось на сайте, без миграций и имён файлов. Почему
 * сделано так — в docs/plan.md и в сообщениях коммитов.
 *
 * Из пункта должно быть понятно, что сделано: добавлено, исправлено, изменено,
 * увеличено, убрано. Слово — любое подходящее по смыслу и не обязательно первое:
 * «Добавлен список всех сессий», «Сайт адаптирован под телефон», «Увеличена
 * толщина линий». «Исправлен» — только то, что было сломано уже в прошлой версии.
 * Одно изменение — один пункт. Точки в конце пункта нет, тест сверяет.
 *
 * Номер версии — MAJOR.MINOR.PATCH: MAJOR — сайт переделан заметно для всех,
 * MINOR — новые возможности, PATCH — исправления и мелкая правка вида.
 * Верхняя версия — текущая; она же стоит в package.json, тест сверяет. */

/** Раздел сайта и что в нём поменялось. */
