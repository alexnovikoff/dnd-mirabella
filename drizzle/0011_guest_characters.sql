-- Персонаж — один тип: узел kind = 'character' всегда имеет строку в
-- characters. До этой миграции узел, заведённый с типом «Персонаж» на доске
-- или в базе знаний, строки не получал — у него не было ни страницы
-- /characters/…, ни места в «Партии».
--
-- Такие узлы становятся гостевыми персонажами (is_pc = false): в «Партии»
-- они видны только по кнопке «Показать гостевых», в hero «Хроники» и среди
-- авторов цитат их нет.
--
-- Накатывать ПОСЛЕ деплоя: прежняя сборка выводит в «Партию» каждую строку
-- characters и запрещает удалять любой узел со строкой — гости встали бы
-- в партию и перестали бы удаляться.
INSERT INTO "characters" ("node_id", "is_pc")
SELECT "id", false
  FROM "nodes"
 WHERE "kind" = 'character'
   AND "id" NOT IN (SELECT "node_id" FROM "characters");
